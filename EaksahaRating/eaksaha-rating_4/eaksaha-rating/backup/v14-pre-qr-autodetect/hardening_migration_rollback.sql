DROP TABLE IF EXISTS `rate_limits`;

DROP INDEX `idx_ratings_hidden` ON `ratings`;

ALTER TABLE `ratings`
    DROP COLUMN `hidden_at`,
    DROP COLUMN `hidden_by`,
    DROP COLUMN `hidden_reason`;

SELECT COUNT(*) AS `จำนวนรีวิวที่เหลือ` FROM `ratings`;
