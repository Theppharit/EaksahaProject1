/**
 * ตรวจว่าตอนนี้มีอะไรผิดปกติที่ต้องบอกผู้ใช้คนนี้ไหม
 *
 * @param string $role บทบาทของคนที่กำลังเปิดหน้าอยู่ (admin/manager/sales)
 * @return array<array{level:string,title:string,body:string}>
 *         level: 'info' แจ้งให้ทราบ · 'warn' ใช้ได้บางส่วน · 'down' ใช้ไม่ได้
 */
function notice_banners(?PDO $pdo, string $role): array
{
    $out = [];
    if ($pdo === null) { return $out; }

    // ── 1) AI ค้างไม่ให้ดาว ──
    // อาการที่ผู้ใช้เห็น: รีวิวเข้ามาแล้วแต่ไม่มีดาวสักที
    // ถ้าไม่บอก พนักงานจะนึกว่าลูกค้าไม่ได้ประเมิน แล้วไปรบกวนลูกค้าให้ทำซ้ำ
    if (function_exists('ai_columns_ready') && ai_columns_ready($pdo)) {
        try {
            $st = $pdo->query(
                "SELECT COUNT(*) FROM ratings
                 WHERE ai_status = 'pending' AND created_at < (NOW() - INTERVAL 30 MINUTE)"
            );
            $stuck = (int) ($st ? $st->fetchColumn() : 0);

            if ($stuck > 0) {
                $out[] = $role === 'sales'
                    ? ['level' => 'warn',
                       'title' => 'ระบบให้ดาวอัตโนมัติกำลังมีปัญหา',
                       'body'  => 'รีวิวจากลูกค้าถูกบันทึกไว้ครบแล้ว ไม่มีอะไรหาย '
                                . 'แต่ดาวจะขึ้นช้ากว่าปกติ ตอนนี้มี ' . number_format($stuck)
                                . ' รายการรอคะแนนอยู่ — ทีมผู้ดูแลกำลังแก้ให้ '
                                . 'ไม่ต้องให้ลูกค้าประเมินซ้ำนะครับ']
                    : ['level' => 'warn',
                       'title' => 'มีรีวิว ' . number_format($stuck) . ' รายการค้างรอ AI ให้ดาวเกิน 30 นาที',
                       'body'  => 'มักเกิดจาก API ล่มหรือ key หมดอายุ — ตรวจที่เมนู "ทดสอบ AI ให้ดาว" '
                                . 'แล้วกด "ลองให้ดาวใหม่" ระหว่างนี้คะแนนเฉลี่ยจะยังไม่รวมรายการเหล่านี้'];
            }
        } catch (PDOException $e) {
            // ตัวแจ้งเตือนต้องไม่มีวันทำให้หน้าที่มันไปเกาะอยู่ล้มเสียเอง
        }
    }

    // ── 2) ยังไม่ได้รัน migration ตัวกันรีวิวซ้ำ ──
    // อาการ: ใครถือลิงก์ QR ก็ส่งรีวิวได้ไม่จำกัด ตัวเลขทั้งระบบเชื่อไม่ได้
    // บอกเฉพาะผู้ดูแล เพราะพนักงานขายแก้เรื่องนี้ไม่ได้ และบอกไปก็มีแต่ทำให้กังวล
    if ($role !== 'sales' && function_exists('hidden_columns_ready') && !hidden_columns_ready($pdo)) {
        $out[] = ['level' => 'info',
                  'title' => 'ตัวกันรีวิวซ้ำยังไม่ทำงาน',
                  'body'  => 'ยังไม่ได้รัน hardening_migration.sql — ตอนนี้คนเดียวส่งรีวิวให้พนักงานคนเดิม '
                           . 'ได้ไม่จำกัด และปุ่มซ่อนรีวิวยังใช้ไม่ได้ '
                           . 'เปิด phpMyAdmin → ฐานข้อมูล eaksaha_rating → แท็บ SQL → วางไฟล์ทั้งไฟล์ → Go'];
    }

    return $out;
}

/** วาดแถบทั้งหมด — ไม่มีอะไรผิดปกติก็ไม่วาดอะไรเลย */
function notice_bar(?PDO $pdo, string $role): string
{
    $icons = [
        'info' => '<circle cx="12" cy="12" r="10"/><line x1="12" y1="16" x2="12" y2="12"/><line x1="12" y1="8" x2="12.01" y2="8"/>',
        'warn' => '<path d="M10.29 3.86 1.82 18a2 2 0 0 0 1.71 3h16.94a2 2 0 0 0 1.71-3L13.71 3.86a2 2 0 0 0-3.42 0z"/><line x1="12" y1="9" x2="12" y2="13"/><line x1="12" y1="17" x2="12.01" y2="17"/>',
        'down' => '<circle cx="12" cy="12" r="10"/><line x1="15" y1="9" x2="9" y2="15"/><line x1="9" y1="9" x2="15" y2="15"/>',
    ];

    $html = '';
    foreach (notice_banners($pdo, $role) as $b) {
        $lv = $b['level'];
        $html .= '<div class="sys-note ' . htmlspecialchars($lv) . '">'
               . '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
               . 'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
               . ($icons[$lv] ?? $icons['info']) . '</svg><div>'
               . '<b>' . htmlspecialchars($b['title']) . '</b>'
               . '<span>' . htmlspecialchars($b['body']) . '</span>'
               . '</div></div>';
    }
    return $html;
}
